// Общий кэш ответов API (TanStack Query).
//
// Как работает: ответ сервера запоминается в памяти по «ключу» запроса.
// Пока данные свежие (staleTime), повторный переход на страницу показывает их
// сразу и не ходит на сервер. Когда данные устарели — страница всё равно
// показывает их мгновенно, а свежие подгружает в фоне и тихо подменяет.
//
// Вынесен в отдельный файл, чтобы auth.jsx мог очистить кэш при выходе
// без круговых импортов.

import { QueryClient } from '@tanstack/react-query'

export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 60 * 1000, // минуту данные свежие: переходы туда-обратно — без запросов
      gcTime: 10 * 60 * 1000, // неиспользуемые данные держим в памяти 10 минут
      // Повторяем только сбои сети и сервера (5xx). 401/403/404/422 — повтор не поможет.
      retry: (failureCount, error) => failureCount < 2 && (!error?.status || error.status >= 500),
    },
  },
})
